export function getPerformanceCampaigns() {
  const campaigns = Array.from(new Set(performanceContentData.map((item) => item.campaign)));
  return ['All Campaign', ...campaigns];
}

export function filterAndSortPerformanceContent(
  data = performanceContentData,
  { campaign = 'All Campaign', channel = 'All Channel', metric = 'Engagement' } = {}
) {
  let list = [...data];

  // 1. Filter by Campaign
  if (campaign && campaign !== 'All Campaign') {
    list = list.filter((item) => item.campaign.toLowerCase() === campaign.toLowerCase());
  }

  // 2. Filter by Channel
  if (channel && channel !== 'All Channel') {
    const ch = channel.toLowerCase();
    list = list.filter((item) => {
      const plat = item.platform.toLowerCase();
      const chName = item.channel.toLowerCase();
      if (ch === 'x / twitter' || ch === 'twitter' || ch === 'x') {
        return plat === 'x' || plat === 'twitter' || plat === 'tw';
      }
      return plat.includes(ch) || chName.includes(ch);
    });
  }

  // 3. Sort by Metric
  if (metric === 'Views') {
    list.sort((a, b) => {
      const vA = a.views !== null && a.views !== undefined ? a.views : -1;
      const vB = b.views !== null && b.views !== undefined ? b.views : -1;
      return vB - vA;
    });
  } else if (metric === 'ER%') {
    list.sort((a, b) => {
      const erA = a.engagementRate !== null && a.engagementRate !== undefined ? a.engagementRate : -1;
      const erB = b.engagementRate !== null && b.engagementRate !== undefined ? b.engagementRate : -1;
      return erB - erA;
    });
  } else {
    // Default: Engagement
    list.sort((a, b) => (b.engagement || 0) - (a.engagement || 0));
  }

  // 4. Dynamic rank re-indexing (1 to N)
  return list.map((item, idx) => ({
    ...item,
    dynamicRank: idx + 1
  }));
}

