/**
 * Utility Sanitasi Keamanan Frontend
 * Mencegah Cross-Site Scripting (XSS) pada render data dinamis
 */

export function escapeHtml(str) {
  if (str === null || str === undefined) return '';
  return String(str)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#039;');
}

